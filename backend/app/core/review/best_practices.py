def best_practices(query: str, k: int = 3) -> list[str]:
    q = query or ""
    scored: list[tuple[int, str]] = []
    for kws, tip in _BP:
        hit = sum(1 for w in kws if w in q)
        if hit:
            scored.append((hit, tip))
    scored.sort(key=lambda x: x[0], reverse=True)
    picked = [t for _, t in scored[:k]]
    if not picked:  # query 没命中也给几条通用的兜底
        picked = [_BP[0][1], _BP[3][1], _BP[4][1]]
    return picked
